function report_text = write_plate_report(results, info, output_file)
%WRITE_PLATE_REPORT Print and save a deterministic analytical-model report.

kgcm2_to_kgm2 = 1e-4;

Jp = results.I_tensor_prism_kg_cm2;
Jt = results.I_tensor_thin_kg_cm2;
Jp_eng = results.I_tensor_prism_lbm_in2;

status = 'PASS';
if ~results.checks.pass
    status = 'FAIL';
end

report_text = sprintf([ ...
    '\n%s\n%s\n' ...
    'Source geometry: %s\n' ...
    'Model scope: closed-form geometry only; no oscillation/test data used.\n\n' ...
    'ASSUMPTIONS AND REFERENCE FRAME\n' ...
    '  Finished-plate mass: %.6f kg (user-provided model input)\n' ...
    '  Weight corresponding to this mass at standard gravity: %.6f N = %.6f lbf\n' ...
    '  Uniform through-thickness extrusion: %.6f cm = %.6f in\n' ...
    '  Origin: lower-left corner of the stated outer bounding box, bottom face\n' ...
    '  Axes: +x right, +y up, +z through the thickness\n' ...
    '  Geometry note: %s\n' ...
    '  Small-hole treatment: %s\n\n' ...
    'NET GEOMETRY\n' ...
    '  Planform area: %.9f cm^2\n' ...
    '  Volume: %.9f cm^3\n' ...
    '  Effective uniform density required by the specified mass: %.12f kg/cm^3\n\n' ...
    'CENTER OF GRAVITY\n' ...
    '  [x y z] = [%.9f  %.9f  %.9f] cm\n' ...
    '          = [%.9f  %.9f  %.9f] in\n\n' ...
    'FINITE-THICKNESS CENTROIDAL INERTIA TENSOR [kg*cm^2]\n' ...
    '  [% .9f  % .9f  % .9f]\n' ...
    '  [% .9f  % .9f  % .9f]\n' ...
    '  [% .9f  % .9f  % .9f]\n' ...
    '  IXX = %.9f, IYY = %.9f, IZZ = %.9f kg*cm^2\n' ...
    '  IXY tensor term = %.9f kg*cm^2 (tensor convention: -integral(x*y dm))\n\n' ...
    'FINITE-THICKNESS CENTROIDAL INERTIA TENSOR [lbm*in^2]\n' ...
    '  [% .9f  % .9f  % .9f]\n' ...
    '  [% .9f  % .9f  % .9f]\n' ...
    '  [% .9f  % .9f  % .9f]\n' ...
    '  IXX = %.9f, IYY = %.9f, IZZ = %.9f lbm*in^2\n\n' ...
    'THIN-PLATE COMPARISON [kg*cm^2]\n' ...
    '  IXX = %.9f, IYY = %.9f, IZZ = %.9f\n' ...
    '  Finite-thickness increase in drawing-axis IXX/IYY: %.9f kg*cm^2 each\n\n' ...
    'PRINCIPAL RESULTS - FINITE THICKNESS\n' ...
    '  I1 = %.9f kg*cm^2 = %.9f kg*m^2 = %.9f lbm*in^2\n' ...
    '       e1 = [% .9f  % .9f  % .9f]\n' ...
    '  I2 = %.9f kg*cm^2 = %.9f kg*m^2 = %.9f lbm*in^2\n' ...
    '       e2 = [% .9f  % .9f  % .9f]\n' ...
    '  I3 = %.9f kg*cm^2 = %.9f kg*m^2 = %.9f lbm*in^2\n' ...
    '       e3 = [% .9f  % .9f  % .9f]\n\n' ...
    'ANALYTICAL CHECKS: %s\n' ...
    '  Tensor symmetry error: %.3e\n' ...
    '  Principal-axis orthogonality error: %.3e\n' ...
    '  Principal-axis determinant: %.12f\n' ...
    '  Thin-plate perpendicular-axis error: %.3e kg*cm^2\n' ...
    '  Finite-extrusion identity error: %.3e kg*cm^2\n\n' ...
    'COURSE PENDULUM CONTEXT (not evaluated because d, L, and r were not supplied)\n' ...
    '  Compound: f = (1/(2*pi))*sqrt(m*g*d/(J_CG + m*d^2))\n' ...
    '            d is the pivot-axis-to-CG distance.\n' ...
    '  Bifilar:  f = (1/(2*pi))*sqrt(m*g*r^2/(J_CG*L))\n' ...
    '            L is cable length and r is the suspension radius.\n' ...
    '  Use one consistent unit system and the J_CG for the tested axis.\n'], ...
    info.name, repmat('=',1,length(info.name)), info.source, ...
    results.mass_kg, results.weight_N_standard_g, ...
    results.weight_lbf_standard_g, results.thickness_cm, ...
    results.thickness_in, info.geometry_note, info.holes_note, ...
    results.area_cm2, results.volume_cm3, results.volume_density_kg_cm3, ...
    results.CG_cm, results.CG_in, ...
    Jp(1,:), Jp(2,:), Jp(3,:), diag(Jp), Jp(1,2), ...
    Jp_eng(1,:), Jp_eng(2,:), Jp_eng(3,:), diag(Jp_eng), ...
    diag(Jt), results.mass_kg*results.thickness_cm^2/12, ...
    results.I_principal_prism_kg_cm2(1), ...
    results.I_principal_prism_kg_cm2(1)*kgcm2_to_kgm2, ...
    results.I_principal_prism_lbm_in2(1), ...
    results.principal_axes_prism_rows(1,:), ...
    results.I_principal_prism_kg_cm2(2), ...
    results.I_principal_prism_kg_cm2(2)*kgcm2_to_kgm2, ...
    results.I_principal_prism_lbm_in2(2), ...
    results.principal_axes_prism_rows(2,:), ...
    results.I_principal_prism_kg_cm2(3), ...
    results.I_principal_prism_kg_cm2(3)*kgcm2_to_kgm2, ...
    results.I_principal_prism_lbm_in2(3), ...
    results.principal_axes_prism_rows(3,:), status, ...
    results.checks.tensor_symmetry_error, ...
    results.checks.axes_orthogonality_error, ...
    results.checks.axes_determinant, ...
    results.checks.thin_perpendicular_axis_error, ...
    results.checks.prism_extrusion_identity_error);

fprintf('%s', report_text);

[fid,message] = fopen(output_file, 'w');
if fid < 0
    error('Could not create report file "%s": %s', output_file, message);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', report_text);
end
