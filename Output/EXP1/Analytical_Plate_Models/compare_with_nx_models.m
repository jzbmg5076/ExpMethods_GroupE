%% Compare Simplified Analytical Models with Detailed NX Models
% Uses only analytical geometry and the NX mass-property callouts saved in
% Experiment1_Model_MomentOFInertias.pdf. No experimental data are used.

script_dir = fileparts(mfilename('fullpath'));
if isempty(script_dir)
    script_dir = pwd;
end
output_dir = fullfile(script_dir,'output');

result_files = { ...
    'plate01_notched_solid_results.mat', ...
    'plate02_offset_rectangular_frame_results.mat', ...
    'plate03_irregular_window_frame_results.mat', ...
    'plate04_rectangular_plate_results.mat'};
plate_count = numel(result_files);
analytical = cell(1,plate_count);
for plate_index = 1:plate_count
    result_path = fullfile(output_dir,result_files{plate_index});
    if ~isfile(result_path)
        error(['Missing %s. Run run_all_plate_models.m to generate the ' ...
            'analytical result files first.'],result_path);
    end
    loaded = load(result_path,'plate_results');
    analytical{plate_index} = loaded.plate_results;
end

% Mapped NX callouts, ordered to match analytical Plates 1 through 4.
% Analytical P1 -> NX3; P2 -> NX2; P3 -> NX4; P4 rectangle -> NX1.
nx_model_number = [3; 2; 4; 1];
nx_material = {'Polyethylene'; 'Aluminum_6061'; 'S/Steel_PH15-5'; ...
    'S/Steel_PH15-5'};
% NX Model 1 has zCG=0.2250 in, so its saved CAD thickness is 0.450 in.
nx_thickness_in = [0.500; 0.500; 0.500; 0.450];
nx_cg_callout_in = [ ...
     8.6587, 2.0423, 0.2500; ...
    10.9483, 5.6674, 0.2500; ...
    11.9932, 6.2228, 0.2500; ...
     6.4507, 2.9501, 0.2250];
nx_inertia_native_lbm_in2 = [ ...
      8.1896,   45.0045,   53.1061; ...
    153.1160,  583.9527,  736.6308; ...
    419.2048, 1579.8359, 1997.9787; ...
      9.7186,   46.3077,   55.9135];

kg_to_lbm = 2.204622621848776;
kgcm2_to_lbm_in2 = kg_to_lbm/(2.54^2);
standard_g_m_s2 = 9.80665;
N_per_lbf = 4.4482216152605;

% For a uniform prismatic extrusion whose x/y axes are in the plate plane,
% Ixx + Iyy - Izz = m*t^2/6. This recovers the native CAD mass without
% assuming that the NX material density represents the physical lab part.
nx_mass_lbm = 6*(nx_inertia_native_lbm_in2(:,1) + ...
    nx_inertia_native_lbm_in2(:,2) - ...
    nx_inertia_native_lbm_in2(:,3))./(nx_thickness_in.^2);
nx_mass_kg = nx_mass_lbm/kg_to_lbm;
nx_weight_N = nx_mass_kg*standard_g_m_s2;
nx_weight_lbf = nx_weight_N/N_per_lbf;

nx_inertia_1kg_kg_cm2 = nx_inertia_native_lbm_in2.* ...
    (kg_to_lbm./nx_mass_lbm)/kgcm2_to_lbm_in2;

analytical_cg_in = zeros(plate_count,3);
analytical_inertia_kg_cm2 = zeros(plate_count,3);
analytical_inertia_1kg_kg_cm2 = zeros(plate_count,3);
analytical_mass_kg = zeros(plate_count,1);
for plate_index = 1:plate_count
    analytical_cg_in(plate_index,:) = analytical{plate_index}.CG_in;
    analytical_inertia_kg_cm2(plate_index,:) = ...
        diag(analytical{plate_index}.I_tensor_prism_kg_cm2).';
    analytical_mass_kg(plate_index) = analytical{plate_index}.mass_kg;
    analytical_inertia_1kg_kg_cm2(plate_index,:) = ...
        analytical_inertia_kg_cm2(plate_index,:)/analytical_mass_kg(plate_index);
end

% NX Model3 uses y=0 at the measured raised edge, 6.6 cm above the
% analytical bounding-box origin. Its saved view is horizontally reflected,
% but its x callout maps numerically to the analytical left-origin x.
nx_cg_common_in = nx_cg_callout_in;
nx_cg_common_in(1,2) = nx_cg_common_in(1,2) + 6.6/2.54;

cg_delta_in = nx_cg_common_in - analytical_cg_in;
cg_planar_offset_in = vecnorm(cg_delta_in(:,1:2),2,2);
inertia_delta_kg_cm2 = nx_inertia_1kg_kg_cm2 - ...
    analytical_inertia_1kg_kg_cm2;
inertia_delta_percent = 100*inertia_delta_kg_cm2./ ...
    analytical_inertia_1kg_kg_cm2;
symmetric_difference_percent = 200*abs(inertia_delta_kg_cm2)./ ...
    (abs(nx_inertia_1kg_kg_cm2) + abs(analytical_inertia_1kg_kg_cm2));

% Plate 1 sensitivity: put the normalized NX prism at the measured 0.75-in
% thickness while preserving its planform distribution and 1-kg mass.
plate1_matlab_thickness_cm = analytical{1}.thickness_cm;
plate1_nx_thickness_cm = nx_thickness_in(1)*2.54;
plate1_thickness_adjustment = ...
    (plate1_matlab_thickness_cm^2 - plate1_nx_thickness_cm^2)/12;
plate1_nx_harmonized_kg_cm2 = nx_inertia_1kg_kg_cm2(1,:);
plate1_nx_harmonized_kg_cm2(1:2) = ...
    plate1_nx_harmonized_kg_cm2(1:2) + plate1_thickness_adjustment;

report_file = fullfile(output_dir,'nx_comparison_results.txt');
[fid,message] = fopen(report_file,'w');
if fid < 0
    error('Could not create report file "%s": %s',report_file,message);
end
cleanup_file = onCleanup(@() fclose(fid));

emit_line(fid,'NX / SIMPLIFIED ANALYTICAL PLATE COMPARISON\n');
emit_line(fid,'===========================================\n');
emit_line(fid,['Source: EXP1/Lab/Models_NX/' ...
    'Experiment1_Model_MomentOFInertias.pdf\n']);
emit_line(fid,'No experimental measurements are used.\n\n');
emit_line(fid,'MASS BASIS\n');
emit_line(fid,['  MATLAB uses the user-provided finished masses shown below. ' ...
    'For inertia comparison only, both MATLAB and NX are divided by their ' ...
    'respective masses and reported on a common 1.000000 kg basis.\n']);
emit_line(fid,['  The inferred NX masses below describe the saved CAD ' ...
    'materials/geometries only; they are not predicted physical weights.\n\n']);

emit_line(fid,'MODEL MAPPING AND NATIVE NX PROPERTIES\n');
for plate_index = 1:plate_count
    emit_line(fid,['  Plate %d -> NX Model%d | %-16s | t = %.3f in | ' ...
        'MATLAB m = %.6f kg | inferred NX m = %.6f kg | ' ...
        'implied NX W = %.6f N = %.6f lbf\n'], ...
        plate_index,nx_model_number(plate_index), ...
        nx_material{plate_index},nx_thickness_in(plate_index), ...
        analytical_mass_kg(plate_index),nx_mass_kg(plate_index), ...
        nx_weight_N(plate_index), ...
        nx_weight_lbf(plate_index));
    emit_line(fid,'    Native NX I = [%10.4f %10.4f %10.4f] lbm*in^2\n', ...
        nx_inertia_native_lbm_in2(plate_index,:));
end
emit_line(fid,'\n');

emit_line(fid,'CG COMPARISON IN A COMMON FRAME [in]\n');
emit_line(fid,['  Delta convention: NX - MATLAB. Plate 1 NX y was shifted ' ...
    'by +6.6 cm/2.54 to register the origins.\n']);
for plate_index = 1:plate_count
    emit_line(fid,['  Plate %d: MATLAB [%10.6f %10.6f %8.4f] | ' ...
        'NX [%10.6f %10.6f %8.4f]\n'],plate_index, ...
        analytical_cg_in(plate_index,:),nx_cg_common_in(plate_index,:));
    emit_line(fid,['           NX-MAT [%+10.6f %+10.6f %+8.4f] | ' ...
        'planar offset = %.6f in (%.6f mm)\n'], ...
        cg_delta_in(plate_index,:),cg_planar_offset_in(plate_index), ...
        25.4*cg_planar_offset_in(plate_index));
end

emit_line(fid,['\nMOMENT COMPARISON AFTER NORMALIZING BOTH MATLAB AND NX ' ...
    'TO 1.000 kg [kg*cm^2]\n']);
emit_line(fid,['  Signed delta = NX(1 kg) - MATLAB(1 kg). Symmetric ' ...
    'difference is reported because neither model is ground truth.\n']);
component_names = {'IXX','IYY','IZZ'};
for plate_index = 1:plate_count
    emit_line(fid,'  Plate %d / NX Model%d:\n', ...
        plate_index,nx_model_number(plate_index));
    for component_index = 1:3
        emit_line(fid,['    %s: MATLAB = %12.6f | NX = %12.6f | ' ...
            'delta = %+11.6f (%+8.4f%%) | symmetric diff = %.4f%%\n'], ...
            component_names{component_index}, ...
            analytical_inertia_1kg_kg_cm2(plate_index,component_index), ...
            nx_inertia_1kg_kg_cm2(plate_index,component_index), ...
            inertia_delta_kg_cm2(plate_index,component_index), ...
            inertia_delta_percent(plate_index,component_index), ...
            symmetric_difference_percent(plate_index,component_index));
    end
end

emit_line(fid,'\nPLATE 1 THICKNESS-HARMONIZED SENSITIVITY [kg*cm^2]\n');
emit_line(fid,['  NX Model3 uses t = 0.500 in; MATLAB uses the measured ' ...
    't = 0.750 in. At 1 kg, adjusting only NX thickness gives\n']);
emit_line(fid,'  NX harmonized I = [%12.6f %12.6f %12.6f].\n', ...
    plate1_nx_harmonized_kg_cm2);

emit_line(fid,'\nINTERPRETATION\n');
emit_line(fid,['  Plate 1: The planar CG offset is about 0.0005 in. ' ...
    'The normalized drawing-axis moments differ by at most 0.62%%; after ' ...
    'harmonizing thickness, all three differ by less than 0.05%%.\n']);
emit_line(fid,['  Plate 2: The roughly 0.215 in CG offset and 4-5%% inertia ' ...
    'differences mainly reflect the different NX opening geometry versus ' ...
    'the simplified measured opening.\n']);
emit_line(fid,['  Plate 3: In-plane CGs agree within about 0.001 in, and ' ...
    'normalized inertias agree within about 0.02%%.\n']);
emit_line(fid,['  Plate 4: In-plane CGs agree within about 0.001 in. ' ...
    'After matching mass, normalized inertias agree closely; remaining ' ...
    'differences reflect exact hole/edge geometry and thickness.\n']);
emit_line(fid,['  Small residuals are expected because NX retains detailed ' ...
    'hole cutouts and exact CAD profiles, while MATLAB intentionally uses ' ...
    'simplified closed-form boundaries.\n']);
emit_line(fid,['  NX callouts are rounded to four decimal places, so inferred ' ...
    'masses and normalized values are approximate.\n']);

clear cleanup_file
fprintf('Saved NX comparison report: %s\n',report_file);

function emit_line(fid,format_text,varargin)
line_text = sprintf(format_text,varargin{:});
fprintf('%s',line_text);
fprintf(fid,'%s',line_text);
end
