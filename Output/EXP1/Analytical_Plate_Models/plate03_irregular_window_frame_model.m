%% Plate 3 - Irregular Polygon-Window Frame Analytical Model
% Exact outer-rectangle minus measured concave-polygon area integrals.
% Measurements are from page 5 of Plate_measurements.pdf.

close all;

script_dir = fileparts(mfilename('fullpath'));
if isempty(script_dir)
    script_dir = pwd;
end
addpath(script_dir);
output_dir = fullfile(script_dir,'output');
if ~exist(output_dir,'dir')
    mkdir(output_dir);
end

%% User and measurement inputs
mass_kg = 9.052279652;      % User-provided finished-plate mass [kg]
cm_per_in = 2.54;

% Page 5 does not repeat a thickness label. The adjacent measured aluminum
% frame on page 4 is labeled 0.5 in, so 0.5 in is a visible, editable model
% assumption here rather than a claimed page-5 measurement.
thickness_in = 0.500;     % Assumption [in] - edit if independently measured
thickness_cm = cm_per_in*thickness_in;

outer_width_cm = 61.1;
outer_height_cm = 30.4;

% Opening vertices transcribed from the coordinate labels in the PDF.
% They are ordered counterclockwise around the concave opening.
opening_cm = [ ...
     8.6,  7.6; ...
    20.9,  4.4; ...
    21.8,  8.1; ...
    32.3,  8.1; ...
    52.1,  2.7; ...
    55.5, 16.1; ...
    13.7, 27.2];

outer_cm = [0,0; outer_width_cm,0; ...
    outer_width_cm,outer_height_cm; 0,outer_height_cm];

solid_polygons = {outer_cm};
void_polygons = {opening_cm};
hole_diameter_in = 0.184;  % Assumed equal to the measured Plate-1 holes
hole_edge_offset_in = 0.250; % User-directed nominal center-to-edge offset
circular_voids_in = rectangular_perimeter_holes( ...
    outer_width_cm/cm_per_in,outer_height_cm/cm_per_in,5,5, ...
    hole_edge_offset_in,hole_diameter_in/2);
circular_voids_cm = circular_voids_in*cm_per_in;

%% Closed-form center of gravity and inertias
plate_results = analytical_extruded_plate(solid_polygons, void_polygons, ...
    circular_voids_cm, thickness_cm, mass_kg);

info.name = 'Plate 3 - Irregular Polygon-Window Frame';
info.source = 'Plate_measurements.pdf page 5';
info.geometry_note = ['Concave opening uses all seven labeled vertex ' ...
    'coordinates; page-5 thickness is assumed as 0.5 in.'];
info.holes_note = sprintf(['Included: %d evenly spaced perimeter holes. ' ...
    'Diameter %.3f in is carried from Plate 1; centers use the user-directed ' ...
    'nominal %.3f in edge offset.'],size(circular_voids_in,1), ...
    hole_diameter_in,hole_edge_offset_in);

report_file = fullfile(output_dir,'plate03_irregular_window_frame_results.txt');
write_plate_report(plate_results,info,report_file);
data_file = fullfile(output_dir,'plate03_irregular_window_frame_results.mat');
save(data_file,'plate_results','info','outer_cm','opening_cm', ...
    'circular_voids_cm');

%% Dimensioned analytical figure
outer_in = outer_cm/cm_per_in;
opening_in = opening_cm/cm_per_in;
solid_polygons_in = {outer_in};
void_polygons_in = {opening_in};
outer_width_in = outer_width_cm/cm_per_in;
outer_height_in = outer_height_cm/cm_per_in;

title_lines = { ...
    'Plate 3 - Irregular Polygon-Window Frame', ...
    sprintf(['Analytical footprint | m = %.3f kg ' ...
    '(W = %.3f lbf at standard g) | assumed t = %.3f in'], ...
    mass_kg,plate_results.weight_lbf_standard_g,thickness_in), ...
    sprintf('%d x dia %.3f in holes | nominal center offset %.3f in', ...
    size(circular_voids_in,1),hole_diameter_in,hole_edge_offset_in)};
[fig,ax] = draw_plate_footprint(solid_polygons_in,void_polygons_in, ...
    plate_results,title_lines,[-8.0,69.5,-5.5,36.5]/cm_per_in,'in', ...
    circular_voids_in);

dimension_color = [0.08,0.28,0.62];
draw_linear_dimension(ax,[0,outer_height_in], ...
    [outer_width_in,outer_height_in],3.0/cm_per_in, ...
    sprintf('%.3f in overall',outer_width_in),dimension_color);
draw_linear_dimension(ax,[outer_width_in,0], ...
    [outer_width_in,outer_height_in],-3.3/cm_per_in, ...
    sprintf('%.3f in overall',outer_height_in),dimension_color);

label_offsets_in = [ ...
    -4.8,  0.4; ...
    -4.8, -1.1; ...
    -4.4,  0.9; ...
     0.5,  0.9; ...
     0.6, -1.0; ...
     0.6,  0.7; ...
     0.5,  0.9]/cm_per_in;
for k = 1:size(opening_in,1)
    plot(ax,opening_in(k,1),opening_in(k,2),'o', ...
        'MarkerSize',5,'MarkerFaceColor',[0.55,0.10,0.10], ...
        'MarkerEdgeColor',[0.55,0.10,0.10]);
    text(ax,opening_in(k,1)+label_offsets_in(k,1), ...
        opening_in(k,2)+label_offsets_in(k,2), ...
        sprintf('(%.3f, %.3f) in',opening_in(k,1),opening_in(k,2)), ...
        'Color',[0.55,0.10,0.10],'FontWeight','bold','FontSize',9, ...
        'BackgroundColor','white','Margin',1);
end
text(ax,38.0/cm_per_in,20.0/cm_per_in, ...
    sprintf('CONCAVE OPENING\nvertices in inches'), ...
    'HorizontalAlignment','center','FontWeight','bold', ...
    'Color',[0.20,0.20,0.20],'BackgroundColor','white','Margin',2);

figure_file = fullfile(output_dir,'plate03_irregular_window_frame_geometry.png');
exportgraphics(fig,figure_file,'Resolution',300);
fprintf('Saved dimensioned figure: %s\n',figure_file);
fprintf('Saved text results:      %s\n',report_file);
fprintf('Saved MATLAB results:    %s\n',data_file);
